#!/usr/bin/env bash
# 生成可双击的 尘迹拉力.app（放在仓库根目录；不签名、不公证；可以自己拖进"应用程序"或程序坞）。
# 双击 = ./play-stable.sh（玩 builds/stable）。App 里记着仓库的绝对路径，挪走 App 也能找到游戏；挪动仓库后重新运行本脚本。
#   scripts/make-app.sh [输出目录，默认仓库根目录]
set -euo pipefail
cd "$(dirname "$0")/.."
ROOT="$(pwd -P)"
OUT="${1:-$ROOT}"
APP="$OUT/尘迹拉力.app"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# icon: a square crop of the title art around the car → iconset → icns
SRC=public/assets/ui/title_key.jpg
sips -s format png "$SRC" --out "$TMP/full.png" >/dev/null
sips --cropOffset 290 1010 -c 900 900 "$TMP/full.png" --out "$TMP/square.png" >/dev/null
mkdir -p "$TMP/icon.iconset"
for s in 16 32 128 256 512; do
  sips -z $s $s "$TMP/square.png" --out "$TMP/icon.iconset/icon_${s}x${s}.png" >/dev/null
  d=$((s * 2)); [ $d -gt 900 ] && d=900
  sips -z $d $d "$TMP/square.png" --out "$TMP/icon.iconset/icon_${s}x${s}@2x.png" >/dev/null
done
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"
iconutil -c icns "$TMP/icon.iconset" -o "$APP/Contents/Resources/dustmark.icns"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>尘迹拉力</string>
  <key>CFBundleDisplayName</key><string>尘迹拉力 DUSTMARK</string>
  <key>CFBundleIdentifier</key><string>local.dustmark.rally</string>
  <key>CFBundleVersion</key><string>1</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>dustmark</string>
  <key>CFBundleIconFile</key><string>dustmark</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>LSUIElement</key><false/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/dustmark" <<LAUNCHER
#!/bin/bash
# 尘迹拉力.app launcher → play-stable.sh (generated by scripts/make-app.sh)
ROOT="$ROOT"
# Finder starts apps with a bare PATH: add Homebrew / the usual Node locations
export PATH="/opt/homebrew/bin:/usr/local/bin:\$HOME/.volta/bin:\$HOME/.local/bin:\$PATH"
LOG="\$HOME/Library/Logs/dustmark.log"
say_err() { /usr/bin/osascript -e "display dialog \"\$1\" with title \"尘迹拉力\" buttons {\"好\"} default button 1 with icon caution" >/dev/null 2>&1; }
[ -x "\$ROOT/play-stable.sh" ] || { say_err "找不到游戏目录 \$ROOT。挪动过 rally 文件夹的话，在新位置运行 scripts/make-app.sh 重新生成 App。"; exit 1; }
command -v node >/dev/null || { say_err "需要 Node.js：在终端运行 brew install node。"; exit 1; }
[ -f "\$ROOT/builds/stable/index.html" ] || { say_err "还没有稳定版：在终端运行 \$ROOT/scripts/snapshot-stable.sh，或者用 ./play.sh 玩开发版。"; exit 1; }
source "\$ROOT/scripts/launch.sh"
dustmark_find_chrome >/dev/null || { say_err "没找到 Google Chrome。请先安装 Chrome（https://www.google.com/chrome/）。"; exit 1; }
echo "---- \$(date) ----" >> "\$LOG"
"\$ROOT/play-stable.sh" >> "\$LOG" 2>&1 || say_err "启动失败，详情见 ~/Library/Logs/dustmark.log"
LAUNCHER
chmod +x "$APP/Contents/MacOS/dustmark"
printf 'APPL????' > "$APP/Contents/PkgInfo"
plutil -lint "$APP/Contents/Info.plist"
echo "已生成 $APP"
